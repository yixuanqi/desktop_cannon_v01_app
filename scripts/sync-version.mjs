/** package.json is the canonical version. UI files are stamped before builds. */
import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const version=JSON.parse(read('package.json')).version;
const tauri=JSON.parse(read('src-tauri/tauri.conf.json')).version;
const cargo=read('src-tauri/Cargo.toml').match(/^version\s*=\s*"([^"]+)"/m)?.[1];
const lock=read('src-tauri/Cargo.lock').match(/name\s*=\s*"desktop-cannon"\s+version\s*=\s*"([^"]+)"/)?.[1];
for(const [file,value] of [['Tauri',tauri],['Cargo',cargo],['Cargo.lock',lock]]){
  if(value!==version)throw new Error(`version mismatch: ${file}=${value} package=${version}`);
}
const output=path.join(root,'web/js/version.mjs');
const expected=`// Generated by scripts/sync-version.mjs; do not edit by hand.\nexport const APP_VERSION = ${JSON.stringify(version)};\n`;
if(process.argv.includes('--check')){
  if(!fs.existsSync(output)||fs.readFileSync(output,'utf8').replace(/\r\n/g,'\n')!==expected)
    throw new Error('web/js/version.mjs is stale; run node scripts/sync-version.mjs');
}else{
  fs.writeFileSync(output,expected);
}
console.log(`Version ${version}: package, Cargo, Tauri, web stamp consistent`);
